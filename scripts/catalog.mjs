import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const languages = ["Python", "TypeScript", "Go", "Ruby", "Java"];
const manifests = [
  ["TypeScript", "package.json"],
  ["Go", "go.mod"],
  ["Ruby", "Gemfile"],
  ["Java", "build.gradle.kts"],
  ["Python", "pyproject.toml"],
];
const flows = new Map([
  ["mcp-server", "MCP server"],
  ["delegated-access", "Delegated access"],
  ["brokered-credentials", "Brokered credentials"],
  ["a2a-delegation", "A2A delegation"],
  ["workload-identity", "Workload identity"],
  ["agent-frameworks", "Agent frameworks"],
]);
const flowOrder = [...flows.keys()];
const excluded = new Set(["docs", "eval", "scripts"]);
const generated = "<!-- Generated by scripts/catalog.mjs; edit template.json. -->";

function requireMetadata(condition, file, message) {
  if (!condition) throw new Error(file + ": " + message);
}

function isOneLine(value) {
  return typeof value === "string" && value.trim() && !/[\r\n\u2028\u2029]/u.test(value);
}

function readTemplates() {
  const templates = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const { name } = entry;
    if (!entry.isDirectory() || /^[._]/u.test(name) || excluded.has(name)) continue;

    const dir = join(root, name);
    const manifest = manifests.find(([, filename]) =>
      statSync(join(dir, filename), { throwIfNoEntry: false })?.isFile(),
    );
    const file = join(name, "template.json");
    const path = join(root, file);
    if (!statSync(path, { throwIfNoEntry: false })?.isFile()) {
      requireMetadata(!manifest, file, "missing template metadata");
      continue;
    }
    requireMetadata(manifest, file, "no supported language manifest found");

    const source = readFileSync(path, "utf8");
    let template;
    try {
      template = JSON.parse(source);
    } catch (error) {
      throw new Error(file + ": " + error.message);
    }
    requireMetadata(template && template.name === name, file, "name must match the directory");
    const [language, filename] = manifest;
    requireMetadata(template.language === language, file, "language must be " + language + " for " + filename);
    requireMetadata(
      Array.isArray(template.flows) && template.flows.length > 0 && template.flows.every((flow) => flows.has(flow)),
      file,
      "flows must be a nonempty array of known flow IDs",
    );
    requireMetadata(isOneLine(template.framework), file, "framework must be one nonempty line");
    requireMetadata(isOneLine(template.description), file, "description must be one nonempty line");
    requireMetadata(!/[\u2013\u2014]/u.test(JSON.stringify(template)), file, "use hyphens, not en or em dashes");

    const manifestText = readFileSync(join(dir, filename), "utf8");
    requireMetadata(
      Array.isArray(template.sdk_packages) && template.sdk_packages.length > 0
        && template.sdk_packages.every((pkg) => isOneLine(pkg) && manifestText.includes(pkg)),
      file,
      "sdk_packages must be a nonempty array of package names declared in " + filename,
    );
    templates.push(template);
  }

  return templates.sort((a, b) =>
    flowOrder.indexOf(a.flows[0]) - flowOrder.indexOf(b.flows[0])
    || languages.indexOf(a.language) - languages.indexOf(b.language)
    || (a.name < b.name ? -1 : Number(a.name > b.name)),
  );
}

function table(headers, rows) {
  const line = (cells) => "| " + cells.map((cell) => cell.replaceAll("|", "\\|")).join(" | ") + " |";
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

function templateLink({ name }) {
  return "[" + codeSpan(name) + "](./" + encodeURIComponent(name) + ")";
}

function codeSpan(value) {
  return "\x60" + value + "\x60";
}

function readmeTable(templates) {
  return table(
    ["Template", "Flow", "Language", "Framework", "SDK packages", "Description"],
    templates.map((template) => [
      templateLink(template),
      template.flows.map((id) => flows.get(id)).join(", "),
      template.language,
      template.framework,
      template.sdk_packages.map(codeSpan).join(", "),
      template.description,
    ]),
  );
}

function coverageMatrix(templates) {
  return table(
    ["Language", ...flows.values()],
    languages.map((language) => [
      language,
      ...flowOrder.map((flow) => templates
        .filter((template) => template.language === language && template.flows.includes(flow))
        .map(templateLink).join(", ")),
    ]),
  );
}

function renderRegion(file, region, content) {
  const path = join(root, file);
  const current = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
  const begin = "<!-- BEGIN " + region + " -->";
  const end = "<!-- END " + region + " -->";
  const lines = current.split("\n");
  const start = lines.indexOf(begin);
  const stop = lines.indexOf(end);
  if (start < 0 || stop <= start || start !== lines.lastIndexOf(begin) || stop !== lines.lastIndexOf(end)) {
    throw new Error(file + ": expected one ordered pair of " + region + " markers");
  }
  lines.splice(start + 1, stop - start - 1, generated, "", content, "");
  return { file, path, current, expected: lines.join("\n") };
}

function main(args) {
  const check = args.length === 1 && args[0] === "--check";
  if (args.length && !check) throw new Error("Usage: node scripts/catalog.mjs [--check]");

  const templates = readTemplates();
  const updates = [
    renderRegion("README.md", "TEMPLATE TABLE", readmeTable(templates)),
    renderRegion("CATALOG.md", "COVERAGE MATRIX", coverageMatrix(templates)),
  ].filter(({ current, expected }) => current !== expected);

  if (check && updates.length) {
    throw new Error("Stale template catalog: " + updates.map(({ file }) => file).join(", ")
      + ". Run node scripts/catalog.mjs.");
  }
  for (const { path, expected } of updates) writeFileSync(path, expected);
  console.log(check ? "Template catalog is up to date." : "Template catalog generated.");
}

try {
  main(process.argv.slice(2));
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
